#!/usr/bin/env python3
"""Generates packages/sdk/src/registryEvents.ts from the registry's interface (#134).

    python scripts/gen-events.py

Reads every `contractevent` in contracts/interfaces/registry.rs (written by
scripts/contract-snapshots.sh) and writes a typed decoder for each. The SDK
test `registryEvents.test.ts` fails when the interface has an event or field
the generated file doesn't, so rerun this after changing events.rs.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INTERFACE = ROOT / "contracts" / "interfaces" / "registry.rs"
OUT = ROOT / "packages" / "sdk" / "src" / "registryEvents.ts"

KINDS = {
    "u64": ("u64", "bigint"),
    "i128": ("i128", "bigint"),
    "u32": ("u32", "number"),
    "bool": ("bool", "boolean"),
    "Address": ("address", "string"),
    "BytesN<32>": ("bytes", "Uint8Array"),
    "Option<Address>": ("option_address", "string | undefined"),
}


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p.capitalize() for p in rest)


def parse():
    src = INTERFACE.read_text(encoding="utf-8")
    pattern = re.compile(
        r'#\[soroban_sdk::contractevent\(topics = \["([a-z_]+)"\][^\]]*\]\s*#\[derive[^\]]*\]\s*pub struct (\w+) \{(.*?)\}',
        re.S,
    )
    events = []
    for name, struct, body in pattern.findall(src):
        fields = []
        for topic, field, ty in re.findall(r"(#\[topic\]\s*)?pub (\w+): ([^,]+),", body):
            ty = ty.replace("soroban_sdk::", "").strip()
            if ty not in KINDS:
                raise SystemExit(f"{struct}.{field}: no decoder for type {ty}; add it to KINDS")
            fields.append((field, KINDS[ty][0], KINDS[ty][1], bool(topic)))
        events.append((name, struct, fields))
    return sorted(events)


def main():
    events = parse()
    lines = [
        "/**",
        " * Typed decoders for every registry event (#134). Generated by",
        " * scripts/gen-events.py from contracts/interfaces/registry.rs; don't edit",
        " * by hand. `registryEvents.test.ts` fails when the contract gains an event",
        " * or field this file doesn't know.",
        " */",
        'import type { RegistryEvent } from "./events.js";',
        "",
        "/** How each field is encoded on-chain. */",
        'export type FieldKind = "u64" | "i128" | "u32" | "bool" | "address" | "bytes" | "option_address";',
        "",
        "/** Per event: its topic fields (after the name) and data fields, in order. */",
        "export const EVENT_SPECS: Record<string, { topics: [string, FieldKind][]; data: [string, FieldKind][] }> = {",
    ]
    for name, _, fields in events:
        topics = ", ".join(f'["{f}", "{k}"]' for f, k, _, t in fields if t)
        data = ", ".join(f'["{f}", "{k}"]' for f, k, _, t in fields if not t)
        lines.append(f"  {name}: {{ topics: [{topics}], data: [{data}] }},")
    lines += ["};", "", "/** Fields every decoded event carries, from the RPC server. */",
              "export interface EventMeta {", "  ledger: number;", "  closedAt: string;", "  txHash: string;",
              "  /** Opaque, ordered id; usable as a cursor. */", "  id: string;", "}", ""]
    for name, struct, fields in events:
        lines.append(f"export interface {struct}Event extends EventMeta {{")
        lines.append(f'  type: "{name}";')
        for f, _, ts, _ in fields:
            lines.append(f"  {camel(f)}: {ts};")
        lines.append("}")
    lines.append("")
    lines.append("/** Any registry event, discriminated by `type`. */")
    lines.append("export type TypedRegistryEvent =")
    for i, (_, struct, _) in enumerate(events):
        lines.append(f"  | {struct}Event" + (";" if i == len(events) - 1 else ""))
    lines += [
        "",
        "export type RegistryEventType = TypedRegistryEvent[\"type\"];",
        "",
        "const camel = (s: string) => s.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());",
        "",
        "function convert(value: unknown, kind: FieldKind): unknown {",
        "  switch (kind) {",
        '    case "u64":',
        '    case "i128":',
        "      return BigInt(value as bigint);",
        '    case "u32":',
        "      return Number(value);",
        '    case "bool":',
        "      return Boolean(value);",
        '    case "address":',
        "      return String(value);",
        '    case "bytes":',
        "      return value instanceof Uint8Array ? new Uint8Array(value) : new Uint8Array();",
        '    case "option_address":',
        "      return value === null || value === undefined ? undefined : String(value);",
        "  }",
        "}",
        "",
        "/**",
        " * Decodes a registry event into its typed form, with camelCase fields.",
        " * Returns `undefined` for an event this SDK doesn't know, or one missing a",
        " * field it expects (both mean a newer registry), rather than throwing.",
        " */",
        "export function decodeEvent(e: RegistryEvent): TypedRegistryEvent | undefined {",
        "  const spec = EVENT_SPECS[e.name];",
        "  if (!spec) return undefined;",
        "  const out: Record<string, unknown> = { type: e.name, ledger: e.ledger, closedAt: e.closedAt, txHash: e.txHash, id: e.id };",
        "  const fields: [string, FieldKind, unknown][] = [",
        "    ...spec.topics.map(([field, kind], i): [string, FieldKind, unknown] => [field, kind, e.topics[i]]),",
        "    ...spec.data.map(([field, kind]): [string, FieldKind, unknown] => [field, kind, e.data[field]]),",
        "  ];",
        "  for (const [field, kind, value] of fields) {",
        '    if (value === undefined && kind !== "option_address") return undefined;',
        "    out[camel(field)] = convert(value, kind);",
        "  }",
        "  return out as unknown as TypedRegistryEvent;",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} with {len(events)} events")


if __name__ == "__main__":
    main()
